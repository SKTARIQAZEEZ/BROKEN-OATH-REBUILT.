import assert from "node:assert/strict";
import * as THREE from "three";
import {VehicleSystem} from "../src/vehicle-system.js";
const scene=new THREE.Scene();
const environment={colliders:[{x:0,z:0,halfX:2,halfZ:2,height:4}],walkableBounds:{minX:-28,maxX:28,minZ:-28,maxZ:28}};
const messages=[];
const vehicles=new VehicleSystem({scene,onMessage:m=>messages.push(m)});
assert.equal(vehicles.loadChapter(1,environment),null,"school chapter intentionally has no drivable car");
assert.ok(vehicles.loadChapter(3,environment),"operation chapter should receive a drivable vehicle");
assert.ok(vehicles.collider,"parked vehicle must register a physical collider");
const vehicleParts=vehicles.vehicle.children.map(part=>part.name);
for(const part of ["front-grille","front-windshield","rear-windshield","side-mirror","door-handle","wheel-arch-trim","brake-disc","front-bumper","rear-bumper","roof-rail","exhaust-tip"]){
 assert.ok(vehicleParts.includes(part),"vehicle exterior should include "+part);
}
assert.equal(vehicles.vehicle.userData.wheels.length,4,"all four wheels must remain independently animated");
assert.ok(environment.colliders.includes(vehicles.collider),"parked vehicle must block on-foot movement");
const player=new THREE.Group();player.position.copy(vehicles.position).add(new THREE.Vector3(0,0,3));scene.add(player);
assert.deepEqual(vehicles.toggle(player),{ok:true,driving:true});
assert.equal(player.visible,false,"player mesh hides while seated");
assert.ok(environment.colliders.includes(vehicles.collider),"moving vehicle must remain a live obstacle for AI and other actors");
vehicles.update(.5,{forward:true},player);
assert.ok(vehicles.speed>0,"throttle must accelerate the vehicle");
assert.ok(vehicles.position.z<vehicles.collider.z+2,"vehicle must move under throttle");
const preBrake=vehicles.speed;vehicles.brake(.05);assert.ok(vehicles.speed<preBrake,"handbrake must reduce speed");
vehicles.update(.5,{forward:true},player);
const barrier={x:vehicles.position.x,z:vehicles.position.z-4.5,halfX:2,halfZ:.5,height:2};environment.colliders.push(barrier);
const beforeImpact=vehicles.position.clone();vehicles.update(.5,{forward:true},player);
assert.ok(vehicles.position.z>barrier.z+barrier.halfZ+1.95,"vehicle must stop on the near side of solid cover");assert.equal(vehicles.speed,0,"collision must stop vehicle momentum");
environment.colliders=environment.colliders.filter(c=>c!==barrier);
assert.equal(vehicles.toggle(player).driving,false,"V toggles back to on-foot mode");
assert.equal(player.visible,true,"player mesh returns after exiting");
assert.ok(environment.colliders.includes(vehicles.collider),"vehicle collider remains registered after exit");
assert.ok(messages.some(m=>m.includes("ENTERED")));
vehicles.toggle(player);
vehicles.loadChapter(4,environment);
assert.equal(player.visible,true,"chapter transition while driving must restore the player mesh");
assert.equal(vehicles.driving,false);
assert.ok(vehicles.vehicle,"new chapter receives its own vehicle");
vehicles.dispose();
console.log("Vehicle system checks passed: chapter spawning, enter/exit, acceleration, collision registration and chapter transitions.");
